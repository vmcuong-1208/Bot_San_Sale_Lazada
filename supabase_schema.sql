-- ============================================================
-- SCRIPT MỞ QUYỀN TRUY CẬP ROW LEVEL SECURITY (RLS) TRÊN SUPABASE
-- Chạy đoạn này trong SQL Editor của Supabase để cấp quyền cho Anon Key
-- ============================================================

-- 1. Đảm bảo bảng products đã tồn tại
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT UNIQUE NOT NULL,
    title TEXT DEFAULT '',
    variant_name TEXT DEFAULT '',
    current_price NUMERIC DEFAULT 0,
    target_price NUMERIC NOT NULL,
    lowest_price NUMERIC DEFAULT 0,
    discount_amount NUMERIC DEFAULT 0,
    discount_percent NUMERIC DEFAULT 0,
    variants_json JSONB DEFAULT '[]'::jsonb,
    status TEXT DEFAULT 'Đang theo dõi',
    last_checked TEXT DEFAULT '',
    created_at TEXT DEFAULT ''
);

-- Tự động thêm các cột mới nếu bảng đã tồn tại từ trước
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS discount_amount NUMERIC DEFAULT 0;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS discount_percent NUMERIC DEFAULT 0;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS variants_json JSONB DEFAULT '[]'::jsonb;

-- 2. Tắt hoàn toàn RLS trên bảng products
ALTER TABLE public.products DISABLE ROW LEVEL SECURITY;

-- 3. Tạo Policy cho phép public / anon đọc, ghi, sửa, xóa thoải mái (phòng khi Supabase bật lại RLS)
DROP POLICY IF EXISTS "Allow public all access" ON public.products;
CREATE POLICY "Allow public all access" ON public.products
    FOR ALL
    TO public
    USING (true)
    WITH CHECK (true);

-- 4. Cấp quyền truy cập trực tiếp cho role anon và authenticated
GRANT ALL ON TABLE public.products TO anon;
GRANT ALL ON TABLE public.products TO authenticated;
GRANT ALL ON TABLE public.products TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
