-- Script khởi tạo bảng products trên Supabase (PostgreSQL)
-- Chạy đoạn SQL này trong mục "SQL Editor" trên giao diện Supabase

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT UNIQUE NOT NULL,
    title TEXT DEFAULT '',
    variant_name TEXT DEFAULT '',
    current_price NUMERIC DEFAULT 0,
    target_price NUMERIC NOT NULL,
    lowest_price NUMERIC DEFAULT 0,
    status TEXT DEFAULT 'Đang theo dõi',
    last_checked TEXT DEFAULT '',
    created_at TEXT DEFAULT ''
);

-- Tắt Row Level Security (RLS) để cho phép cả Web Streamlit và Worker đọc/ghi dữ liệu bằng Anon Key
ALTER TABLE public.products DISABLE ROW LEVEL SECURITY;

